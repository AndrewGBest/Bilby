//! The graphical store. One Slint window, three layouts (desktop, phone, TV), all
//! drawing the same `Store` (declared in `ui/types.slint`), which this crate fills in
//! from `bilby-core`.
//!
//! [`App`] is the one controller behind the window. Its state is declared here; what it
//! does is spread over the modules below, one per part of the store, each adding its
//! own `impl App`. [`build`] connects every callback of the interface to one of those
//! methods, and [`run`] starts the program.
//!
//! Threading: the interface's thread never waits on the network. Every catalog call
//! goes through `App::job`, which runs the work on a worker thread and hands the
//! result back to the interface's thread. Under test the same code runs inline, so the
//! tests exercise the real handlers.

